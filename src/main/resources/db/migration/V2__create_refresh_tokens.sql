-- Opaque rotating refresh tokens. Only a SHA-256 hash of each token is stored.
-- Tokens issued from the same login share a family_id.
--   expires_at         : inactivity limit of this token (capped at session_expires_at)
--   session_expires_at : absolute limit of the whole family, fixed at login, never extended by rotation
--   revoked_reason     : ROTATED (normal refresh), LOGOUT, or REUSE_DETECTED (replay of a rotated token)
CREATE TABLE refresh_tokens (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash         VARCHAR(64)  NOT NULL,
    family_id          UUID         NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL,
    expires_at         TIMESTAMPTZ  NOT NULL,
    session_expires_at TIMESTAMPTZ  NOT NULL,
    revoked_at         TIMESTAMPTZ,
    revoked_reason     VARCHAR(20),
    replaced_by_id     BIGINT REFERENCES refresh_tokens (id),
    CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_expiry_within_session CHECK (expires_at <= session_expires_at),
    CONSTRAINT ck_refresh_tokens_revocation_consistent CHECK ((revoked_at IS NULL) = (revoked_reason IS NULL)),
    CONSTRAINT ck_refresh_tokens_revoked_reason CHECK (revoked_reason IN ('ROTATED', 'LOGOUT', 'REUSE_DETECTED'))
);

CREATE INDEX idx_refresh_tokens_family_id ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);
