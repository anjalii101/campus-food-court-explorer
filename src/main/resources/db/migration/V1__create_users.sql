-- Users (maps entity com.campusfoodcourt.campus_foodcourt.entity.User)
CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255),
    email    VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(50)  NOT NULL
);

-- Email addresses are unique case-insensitively, enforced by the database itself
-- (the application also stores emails lower-cased). AuthService maps violations of
-- exactly this index to HTTP 409.
CREATE UNIQUE INDEX uk_users_email_lower ON users (lower(email));
